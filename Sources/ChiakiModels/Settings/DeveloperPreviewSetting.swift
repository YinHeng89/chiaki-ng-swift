/// User defaults keys for developer preview options that add sample content to the library.
public enum DeveloperPreviewSetting {
    /// Shows a sample PS5 in the console list.
    public static let samplePS5 = "developer.preview.samplePS5"
    /// Shows a sample PS4 in the console list.
    public static let samplePS4 = "developer.preview.samplePS4"
    /// Adds sample preorders to the cloud library.
    public static let samplePreorders = "developer.preview.samplePreorders"
    /// Draws console cards with layered artwork.
    public static let layeredConsoleCards = "developer.preview.layeredConsoleCards"
    /// Stores the list of sample consoles to add to the library.
    public static let sampleConsoles = "developer.preview.sampleConsoles"
    /// The largest number of sample consoles that can be added.
    public static let mostSampleConsoles = 12
}
